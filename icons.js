function iconSvg(name, size = 18, strokeWidth = 1.8) {
  const paths = ICON_PATHS[name] || '';
  return `<svg class="ico" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${paths}</svg>`;
}

function iconEl(name, size = 18, className = '') {
  const span = document.createElement('span');
  span.className = 'ico-wrap' + (className ? ' ' + className : '');
  span.setAttribute('aria-hidden', 'true');
  span.innerHTML = iconSvg(name, size); // contenido estático, no proviene del usuario
  return span;
}

function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach(el => {
    if (el.dataset.iconDone) return;
    const size = parseInt(el.dataset.iconSize || '18', 10);
    el.innerHTML = iconSvg(el.dataset.icon, size);
    el.setAttribute('aria-hidden', 'true');
    el.dataset.iconDone = '1';
  });
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => hydrateIcons());
} else {
  hydrateIcons();
}
